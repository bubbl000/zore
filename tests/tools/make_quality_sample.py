"""Generates the high-frequency 8K sample used by run_quality_check.ps1.

A 3 px stripe pattern crossed with 11 px bars: downscaling to a 1280-wide fit
turns it into a fine moire grid, exactly the content where a bilinear sample
aliases and a cubic/high-quality filter does not. The reference is generated by
quality_compare.py with Pillow LANCZOS at the same displayed size.

Usage: python make_quality_sample.py <output.png>
"""

import sys

import numpy as np
from PIL import Image


def main() -> int:
    out = sys.argv[1]
    width, height = 7680, 4320
    xs = np.arange(width)
    stripe = ((xs // 3) % 2).astype(np.uint8) * 255
    img = np.tile(stripe, (height, 1))
    ys = np.arange(height)[:, None]
    bars = (((ys // 11) % 2) * 255).astype(np.uint8)
    img = np.where(bars == 255, 255 - img, img)
    rgb = np.stack([img, img, img], axis=2)
    Image.fromarray(rgb).save(out, optimize=False)
    print(f"wrote {out} {width}x{height}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
