#requires -Version 5.1
<#
.SYNOPSIS
    M1-5 ICC check: non-sRGB profiles are converted to sRGB, sRGB profiles are
    left untouched, and the alpha channel survives the conversion.

.DESCRIPTION
    The samples are generated by 测试文件夹\tools\make-color-samples.py:
    icc_linear.* stores values encoded through a linear-gamma profile, so a
    correct conversion must brighten the mid-gray patch from ~55 to ~128.

    Checks:
    - probe/decode report the expected icc state;
    - linear JPEG/PNG decode to the sRGB values;
    - the sRGB-profile JPEG is byte-identical to its profile-less twin;
    - the RGBA PNG keeps its alpha plane exactly.

.EXAMPLE
    python ..\测试文件夹\tools\make-color-samples.py
    powershell -ExecutionPolicy Bypass -File tests\run_icc_check.ps1
#>
param(
    [string]$Cli = (Join-Path (Split-Path -Parent $PSScriptRoot) 'build\Release\zoreview_cli.exe'),
    [string]$Exe = (Join-Path (Split-Path -Parent $PSScriptRoot) 'build\Release\zoreview.exe'),
    [string]$ImageRoot = (Join-Path (Split-Path -Parent (Split-Path -Parent $PSScriptRoot)) '测试文件夹\images'),
    [string]$Out = (Join-Path $PSScriptRoot 'output\icc-screen.png')
)

$ErrorActionPreference = 'Stop'
if (-not (Test-Path -LiteralPath $Cli)) { throw "CLI not found: $Cli" }
if (-not (Test-Path -LiteralPath $Exe)) { throw "exe not found: $Exe" }

$jpeg = Join-Path $ImageRoot 'jpeg'
$png = Join-Path $ImageRoot 'png'
$samples = @(
    (Join-Path $jpeg 'icc_linear.jpg'),
    (Join-Path $jpeg 'icc_linear_plain.jpg'),
    (Join-Path $jpeg 'icc_srgb.jpg'),
    (Join-Path $jpeg 'icc_srgb_plain.jpg'),
    (Join-Path $png 'icc_linear.png'),
    (Join-Path $png 'icc_linear_plain.png'),
    (Join-Path $png 'icc_alpha.png'),
    (Join-Path $png 'icc_alpha_plain.png'),
    (Join-Path $jpeg 'icc_linear_orient6.jpg')
)
foreach ($sample in $samples) {
    if (-not (Test-Path -LiteralPath $sample)) {
        throw "sample missing: $sample (run: python 测试文件夹\tools\make-color-samples.py)"
    }
}

$tmp = Join-Path $env:TEMP 'nv-icc-check'
New-Item -ItemType Directory -Force -Path $tmp | Out-Null
$failures = 0
function Fail([string]$message) { Write-Host "FAIL: $message"; $script:failures++ }

function Parse-Output([string[]]$lines) {
    $map = @{}
    foreach ($line in $lines) {
        $s = [string]$line
        $i = $s.IndexOf(':')
        if ($i -gt 0) { $map[$s.Substring(0, $i).Trim()] = $s.Substring($i + 1).Trim() }
    }
    return $map
}

function Get-Pixel([byte[]]$bytes, [int]$width, [int]$x, [int]$y) {
    $i = (($y * $width) + $x) * 4
    return @([int]$bytes[$i], [int]$bytes[$i + 1], [int]$bytes[$i + 2], [int]$bytes[$i + 3])
}

function Decode([string]$path, [string]$name) {
    $raw = Join-Path $tmp "$name.bgra"
    $output = & $Cli --decode $path --out $raw 2>&1
    if ($LASTEXITCODE -ne 0) { throw "decode failed: $path" }
    return @{ Info = (Parse-Output $output); Pixels = [System.IO.File]::ReadAllBytes($raw) }
}

$linear = Decode (Join-Path $jpeg 'icc_linear.jpg') 'jpeg_linear'
$linearPlain = Decode (Join-Path $jpeg 'icc_linear_plain.jpg') 'jpeg_linear_plain'
$srgb = Decode (Join-Path $jpeg 'icc_srgb.jpg') 'jpeg_srgb'
$srgbPlain = Decode (Join-Path $jpeg 'icc_srgb_plain.jpg') 'jpeg_srgb_plain'
$pngLinear = Decode (Join-Path $png 'icc_linear.png') 'png_linear'
$pngPlain = Decode (Join-Path $png 'icc_linear_plain.png') 'png_linear_plain'
$alpha = Decode (Join-Path $png 'icc_alpha.png') 'png_alpha'
$alphaPlain = Decode (Join-Path $png 'icc_alpha_plain.png') 'png_alpha_plain'
$combined = Decode (Join-Path $jpeg 'icc_linear_orient6.jpg') 'jpeg_linear_orient6'

# Probe/state.
$probeLinear = Parse-Output (& $Cli --probe (Join-Path $jpeg 'icc_linear.jpg') 2>&1)
$probeSrgb = Parse-Output (& $Cli --probe (Join-Path $jpeg 'icc_srgb.jpg') 2>&1)
$probePlain = Parse-Output (& $Cli --probe (Join-Path $jpeg 'icc_linear_plain.jpg') 2>&1)
if ($probeLinear['icc'] -ne 'other') { Fail "probe linear icc=$($probeLinear['icc'])" }
if ($probeSrgb['icc'] -ne 'srgb') { Fail "probe sRGB icc=$($probeSrgb['icc'])" }
if ($probePlain['icc'] -ne 'none') { Fail "probe plain icc=$($probePlain['icc'])" }
if ($linear.Info['icc'] -ne 'converted') { Fail "linear decode icc=$($linear.Info['icc'])" }
if ($srgb.Info['icc'] -ne 'srgb') { Fail "sRGB decode icc=$($srgb.Info['icc'])" }
if ($pngLinear.Info['icc'] -ne 'converted') { Fail "PNG linear decode icc=$($pngLinear.Info['icc'])" }

# Mid-gray patch at (64,64): sRGB 128 -> linear-encoded ~55.
$width = 512
$linearGray = Get-Pixel $linear.Pixels $width 64 64
$plainGray = Get-Pixel $linearPlain.Pixels $width 64 64
$srgbGray = Get-Pixel $srgb.Pixels $width 64 64
$pngLinearGray = Get-Pixel $pngLinear.Pixels $width 64 64
$pngPlainGray = Get-Pixel $pngPlain.Pixels $width 64 64
if ([math]::Abs($linearGray[0] - 128) -gt 3) { Fail "linear JPEG gray=$($linearGray[0]) expected ~128" }
if ([math]::Abs($plainGray[0] - 55) -gt 3) { Fail "plain JPEG gray=$($plainGray[0]) expected ~55" }
if ([math]::Abs($srgbGray[0] - 128) -gt 3) { Fail "sRGB JPEG gray=$($srgbGray[0]) expected ~128" }
if ([math]::Abs($pngLinearGray[0] - 128) -gt 3) { Fail "linear PNG gray=$($pngLinearGray[0]) expected ~128" }
if ([math]::Abs($pngPlainGray[0] - 55) -gt 3) { Fail "plain PNG gray=$($pngPlainGray[0]) expected ~55" }

# sRGB profile must be a no-op: the two files decode identically.
$hasher = [System.Security.Cryptography.SHA256]::Create()
$hashSrgb = [BitConverter]::ToString($hasher.ComputeHash($srgb.Pixels)).Replace('-', '')
$hashSrgbPlain = [BitConverter]::ToString($hasher.ComputeHash($srgbPlain.Pixels)).Replace('-', '')
if ($hashSrgb -ne $hashSrgbPlain) { Fail 'sRGB profile changed the pixels' }

# Alpha: conversion happened on RGB, alpha bytes stay identical.
$alphaCenter = Get-Pixel $alpha.Pixels $width 256 256
$alphaPlainCenter = Get-Pixel $alphaPlain.Pixels $width 256 256
if ($alphaCenter[0] -eq $alphaPlainCenter[0] -and $alphaCenter[1] -eq $alphaPlainCenter[1]) {
    Fail 'RGBA ICC image was not converted'
}
$checker = {
    param([byte[]]$a, [byte[]]$b)
    if ($a.Length -ne $b.Length) { return $false }
    for ($i = 3; $i -lt $a.Length; $i += 4) {
        if ($a[$i] -ne $b[$i]) { return $false }
    }
    return $true
}
if (-not (& $checker $alpha.Pixels $alphaPlain.Pixels)) { Fail 'alpha channel changed by ICC conversion' }
if ($alpha.Info['alpha'] -ne 'yes') { Fail 'RGBA sample did not report alpha' }

# Combined ICC + EXIF 6: upright 384x512, gray patch at source (64,64) lands at
# destination (319,64) and must be converted to ~128 there.
if ($combined.Info['size'] -ne '384x512') { Fail "combined ICC+orientation size=$($combined.Info['size'])" }
if ($combined.Info['orientation'] -ne '6') { Fail "combined ICC+orientation tag=$($combined.Info['orientation'])" }
if ($combined.Info['icc'] -ne 'converted') { Fail "combined ICC+orientation icc=$($combined.Info['icc'])" }
$combinedGray = Get-Pixel $combined.Pixels 384 319 64
if ([math]::Abs($combinedGray[0] - 128) -gt 3) {
    Fail "combined ICC+orientation gray=$($combinedGray[0]) expected ~128"
}

# App log: the main image must be converted.
$logPath = Join-Path $env:LOCALAPPDATA 'ZoreView\logs\zoreview.log'
$logOffset = 0
if (Test-Path -LiteralPath $logPath) { $logOffset = (Get-Item -LiteralPath $logPath).Length }
$outDir = Split-Path -Parent $Out
New-Item -ItemType Directory -Force -Path $outDir | Out-Null
if (Test-Path -LiteralPath $Out) { Remove-Item -LiteralPath $Out -Force }
$app = Start-Process -FilePath $Exe -ArgumentList "--screenshot `"$Out`" --shot-delay 1500 `"$(Join-Path $jpeg 'icc_linear.jpg')`"" -PassThru
if (-not $app.WaitForExit(20000)) { $app.Kill(); throw 'app did not exit' }
$text = ''
if (Test-Path -LiteralPath $logPath) {
    $stream = [System.IO.File]::Open($logPath, 'Open', 'Read', 'ReadWrite')
    try {
        [void]$stream.Seek($logOffset, 'Begin')
        $reader = New-Object System.IO.StreamReader($stream)
        $text = $reader.ReadToEnd()
        $reader.Dispose()
    } finally { $stream.Dispose() }
}
if ($text -notmatch 'icc=converted profile="NV Linear RGB"' -and $text -notmatch 'disk cache hit: .*icc_linear\.jpg') {
    Fail 'app log missing ICC conversion (NV Linear RGB)'
}

Write-Host ("jpeg: linear_gray={0} plain_gray={1} srgb_gray={2}" -f $linearGray[0], $plainGray[0], $srgbGray[0])
Write-Host ("png:  linear_gray={0} plain_gray={1} alpha_center={2}" -f $pngLinearGray[0], $pngPlainGray[0], ($alphaCenter -join ','))
Write-Host "samples=$($samples.Count) screenshot=$Out"
if ($failures -gt 0) { Write-Host "FAIL: $failures check(s)"; exit 1 }
Write-Host 'OK'
